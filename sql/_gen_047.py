        '-- == Reference rows: annual wages ===========================================',
        point_rows('cOESa', DS_ANNUAL, lambda v: v),
        '',
        '-- == Reference rows: derived hourly consulting rate =========================',
        point_rows('cOESh', DS_RATE, lambda v: round(v * RATE_FACTOR, 2)),
        '',
        CONFIG_PREAMBLE,
