def sq(text):
    """Escape a SQL single-quoted literal."""
    return text.replace("'", "''")


def dataset_insert(ds_id, name, source, unit, tier, note, as_of_label):
    return (
        "INSERT INTO reference_datasets\n"
        "  (id, layer, name, source, source_url, unit, geography_scope,\n"
        "   credibility_tier, needs_review, derivation_note, as_of_label,\n"
        "   last_refreshed, refresh_cadence_days, is_active, created_at)\n"
        "VALUES ('{id}', 'L1', '{name}', '{source}',\n"
        "  'https://www.bls.gov/oes/tables.htm', '{unit}', 'national', '{tier}', 1,\n"
        "  '{note}',\n"
        "  '{as_of_label}', '{as_of}', 365, 1, CURRENT_TIMESTAMP);"
    ).format(id=ds_id, name=sq(name), source=sq(source), unit=unit, tier=tier,
             note=sq(note), as_of_label=sq(as_of_label), as_of=AS_OF)


def _join_values(rows):
    """Join (sql, trailing_comment) pairs into a VALUES list.

    The separator must land on the SQL, before the comment — a comma placed after
    a `--` comment is itself commented out, which silently truncates the INSERT.
    """
    out = []
    for i, (sql, comment) in enumerate(rows):
        sep = ',' if i < len(rows) - 1 else ';'
        out.append(sql + sep + ('  -- ' + comment if comment else ''))
    return '\n'.join(out)


def point_rows(prefix, dataset_id, transform):
    rows = []
    for i, (soc, title, p10, p50, p90, emp) in enumerate(ALL_ROWS, start=1):
        v10, v50, v90 = (transform(p10), transform(p50), transform(p90))
        mean = round((v10 + v50 + v50 + v90) / 4.0, 2)
        rows.append((
            "  ('{id}', '{ds}', '{cj}', '{ch}', {p10}, {p50}, {p90}, {mean}, {n}, '{ao}', CURRENT_TIMESTAMP)".format(
                id='{}{:04d}'.format(prefix, i), ds=dataset_id, cj=sq(cjson(soc)),
                ch=chash(soc), p10=v10, p50=v50, p90=v90, mean=mean, n=emp, ao=AS_OF),
            title,
        ))
    return (
        "INSERT INTO reference_data_points\n"
        "  (id, dataset_id, cohort_json, cohort_hash, p10, p50, p90, mean,\n"
        "   sample_size, as_of_date, created_at)\nVALUES\n" + _join_values(rows)
    )


def config_rows():
    rows = []
    for cid, agent, ds, field, label, unit, sigma, note in CONFIGS:
        rows.append((
            ("  ('{id}', '{agent}', 'L1', '{ds}', '{field}', '{label}', '{unit}',\n"
             "   'bayes_precision', '[10, 50, 90]', {sigma}, 300, 40, 8.00, 15.00, 30, 1, CURRENT_TIMESTAMP)"
             ).format(id=cid, agent=agent, ds=ds, field=field, label=sq(label),
                      unit=unit, sigma=sigma),
            note,
        ))
    return (
        "INSERT INTO calibration_configs\n"
        "  (id, agent_key, layer, dataset_id, output_field, field_label, unit,\n"
        "   method, percentiles_json, sigma_model_pct, min_sample_high,\n"
        "   min_sample_moderate, band_floor_pct, drift_threshold_pct,\n"
        "   min_reports_to_reweight, is_enabled, created_at)\nVALUES\n" + _join_values(rows)
    )


