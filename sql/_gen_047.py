def cohort(soc, metro='national', sen='any'):
    return {'soc_group': soc, 'metro': metro, 'seniority': sen}


def chash(soc):
    blob = json.dumps(cohort(soc), sort_keys=True, separators=(',', ':'))
    return hashlib.md5(blob.encode('utf-8')).hexdigest()


def cjson(soc):
    return json.dumps(cohort(soc), sort_keys=True)


