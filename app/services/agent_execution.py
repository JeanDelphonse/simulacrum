"""Per-agent execution config, derived from config/agents.json (EXEC_PLAN P2).

``config/agent_execution.json`` is GENERATED by derive_config() — never edit
it by hand. Regenerate with:

    python -m app.services.agent_execution --write

test_agent_execution.py fails if the file differs from what these rules
produce, so a hand edit cannot survive.

Fields per agent (and no others — the spec forbids inventing fields):
  shape              document | message | sequence | page | config | schedule
  side_effect_class  money_move | send_blast | contractual | public_post |
                     money_link | reversible | none
  hard_gate          True for send_blast, contractual, public_post, money_move
  default_autonomy   L0 generate · L1 plan+suggest · L2 execute w/ per-step
                     approval · L3 execute w/ plan approval. Never L4.
  supported_actions  verbs the artifact supports
  suggested_tools    tool ids (integrations + primitives)
  methods            the named strategy template the agent follows

Owner decisions (EXEC_PLAN §8a) are expressed as rule refinements, not a list
of exceptions: an agent "sends to people" when it emails a list (ConvertKit),
runs a multi-step campaign, produces an email-type artifact, or produces
contacts AND has a sending channel. Research-only integrations (Apollo search
for role_search) therefore classify as ``none``.
"""
from __future__ import annotations

import json
import os
import re

_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CONFIG_PATH = os.path.join(_ROOT, 'config', 'agent_execution.json')

# Most dangerous class wins when several apply (EXEC_PLAN §4, accepted).
CLASS_PRECEDENCE = ('money_move', 'send_blast', 'contractual', 'public_post',
                    'money_link', 'reversible', 'none')
HARD_GATE_CLASSES = frozenset({'send_blast', 'contractual', 'public_post', 'money_move'})

# Page: the label names a page/profile, or the description names a specific
# kind of page. A bare "page" in a description is a length ("a 10-15 page spec").
_PAGE_LABEL_RE = re.compile(r'\bpage\b|membership|linkedin', re.I)
_PAGE_DESC_RE = re.compile(r'\b(landing|sales|booking|opt-in|thank-you|bio|profile) page\b', re.I)
# Schedule: the label names a calendar or schedule (a description's "payment
# schedule" is a section of a contract, not a time-series artifact).
_SCHEDULE_RE = re.compile(r'calendar|schedule', re.I)
_CONFIG_RE = re.compile(r'rate card|\broi\b|allocation|projection|policy|tax|entity|insurance|'
                        r'estate planning|fee structure|pricing|\bfund\b|a/b test', re.I)
_EMAIL_ARTIFACT_RE = re.compile(r'e-?mail|outreach|campaign|reactivation|win-?back|sequence|newsletter', re.I)

_SEND_INTEGRATIONS = frozenset({'apollo', 'internal_email', 'convertkit'})
_PUBLISH_INTEGRATIONS = frozenset({'kajabi', 'convertkit', 'cal_com', 'stripe'})

_BASE_ACTIONS = ['edit', 'preview', 'export', 'copy']
_SHAPE_ACTIONS = {
    'document': [],
    'message': ['send', 'schedule'],
    'sequence': ['step_edit', 'step_preview', 'step_send', 'step_reschedule', 'step_skip',
                 'step_reorder', 'step_insert', 'step_enroll'],
    'page': ['publish', 'get_link', 'connect'],
    'config': ['recompute', 'compare'],
    'schedule': ['entry_publish', 'entry_schedule'],
}

INTEGRATION_TOOLS = {
    'apollo': 'apollo_prospect_search',
    'internal_email': 'send_email',
    'convertkit': 'convertkit_broadcast',
    'cal_com': 'calcom_booking_link',
    'kajabi': 'kajabi_publish',
    'stripe': 'stripe_payment_link',
    'pandadoc': 'pandadoc_send_for_signature',
    'linkedin': 'linkedin_post',
    'alpaca': 'alpaca_order',
}

_METHODS = {
    ('send_blast', 'sequence'): ('outreach_sequence',
                                 ['research', 'personalize', 'send', 'wait', 'follow_up', 'stop_on_reply']),
    ('send_blast', None): ('contact_message',
                           ['select_contacts', 'personalize', 'preview', 'send', 'track_replies']),
    ('contractual', None): ('signature_flow', ['draft', 'review', 'send_for_signature', 'track_signature']),
    ('public_post', None): ('publish_post', ['draft', 'review', 'schedule', 'publish']),
    ('money_link', None): ('payment_link', ['price', 'create_payment_link', 'share_link']),
    ('reversible', 'page'): ('publish_page', ['draft', 'publish', 'get_link']),
    ('reversible', None): ('publish_assets', ['draft', 'publish_assets', 'share']),
    ('money_move', None): ('plan_only', ['plan', 'review']),
    ('none', None): ('generate_only', ['generate', 'refine', 'export']),
}


def _multi_step_agents() -> frozenset:
    from app.services.action_step_service import AGENT_STEP_CONFIG
    return frozenset(AGENT_STEP_CONFIG)


def _shape(agent: dict, multi_step: frozenset) -> str:
    at = agent['action_type']
    label, desc = agent.get('label', ''), agent.get('description', '')
    if at in multi_step:
        return 'sequence'
    if _PAGE_LABEL_RE.search(label) or _PAGE_DESC_RE.search(desc):
        return 'page'
    if _SCHEDULE_RE.search(label):
        return 'schedule'
    if _CONFIG_RE.search(agent.get('label', '')):
        return 'config'
    return 'document'


def _sends_to_people(agent: dict, ints: set, multi_step: frozenset) -> bool:
    text = '%s %s' % (agent.get('label', ''), agent.get('description', ''))
    return bool(
        'convertkit' in ints                                   # emails a list
        or agent['action_type'] in multi_step                  # campaign sequence
        or _EMAIL_ARTIFACT_RE.search(text)                     # email-type artifact
        or (agent.get('produces_contacts') and 'internal_email' in ints))


def _side_effect_class(agent: dict, multi_step: frozenset) -> str:
    ints = set(agent.get('integrations') or [])
    found = set()
    if 'alpaca' in ints:
        found.add('money_move')
    if ints & _SEND_INTEGRATIONS and _sends_to_people(agent, ints, multi_step):
        found.add('send_blast')
    if 'pandadoc' in ints:
        found.add('contractual')
    if 'linkedin' in ints:
        found.add('public_post')
    if ints == {'stripe'}:
        found.add('money_link')
    if ints & _PUBLISH_INTEGRATIONS:
        found.add('reversible')
    # No integrations, or research-only ones (Apollo search with no send).
    found.add('none')
    return next(c for c in CLASS_PRECEDENCE if c in found)


def _default_autonomy(agent: dict, cls: str) -> str:
    if agent.get('layer') == 5:
        return 'L0'                     # Wealth Deployment: generate-only
    if cls in ('money_move', 'send_blast', 'contractual', 'public_post'):
        return 'L1'                     # the send/sign/post/trade step is always confirmed
    if cls in ('reversible', 'money_link'):
        return 'L2'
    return 'L3'


def _entry(agent: dict, multi_step: frozenset) -> dict:
    shape = _shape(agent, multi_step)
    cls = _side_effect_class(agent, multi_step)
    actions = _BASE_ACTIONS + _SHAPE_ACTIONS[shape]
    if agent.get('produces_contacts') or cls == 'send_blast':
        actions = actions + ['send_to_contacts']
    tools = [INTEGRATION_TOOLS[i] for i in (agent.get('integrations') or []) if i in INTEGRATION_TOOLS]
    tools += ['ai_refine', 'export_pdf'] + (['web_research'] if agent.get('research_enabled') else [])
    name, steps = _METHODS.get((cls, shape)) or _METHODS[(cls, None)]
    return {
        'shape': shape,
        'side_effect_class': cls,
        'hard_gate': cls in HARD_GATE_CLASSES,
        'default_autonomy': _default_autonomy(agent, cls),
        'supported_actions': actions,
        'suggested_tools': tools,
        'methods': {'name': name, 'steps': steps},
    }


def derive_config() -> dict:
    """The full config, computed from config/agents.json."""
    from app.services.agent_registry import get_all_agents
    multi_step = _multi_step_agents()
    return {
        'version': 1,
        'generated_from': 'config/agents.json',
        'rules': 'app/services/agent_execution.py',
        'agents': {a['action_type']: _entry(a, multi_step) for a in get_all_agents()},
    }


def write_config(path: str = CONFIG_PATH) -> dict:
    cfg = derive_config()
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(cfg, fh, indent=2, ensure_ascii=False)
        fh.write('\n')
    return cfg


_cache: dict = {}


def load() -> dict:
    if 'cfg' not in _cache:
        with open(CONFIG_PATH, encoding='utf-8') as fh:
            _cache['cfg'] = json.load(fh)
    return _cache['cfg']


def get(action_type: str) -> dict:
    """The execution entry for an agent (aliases resolved); {} if unknown."""
    from app.services.agent_registry import resolve_alias
    return load().get('agents', {}).get(resolve_alias(action_type), {})


def supports(action_type: str, verb: str) -> bool:
    return verb in (get(action_type).get('supported_actions') or [])


if __name__ == '__main__':
    import sys
    sys.path.insert(0, _ROOT)
    os.environ.setdefault('SECRET_KEY', 'generate')
    cfg = write_config() if '--write' in sys.argv else derive_config()
    for at, e in cfg['agents'].items():
        print('%-24s %-9s %-12s %s %s' % (at, e['shape'], e['side_effect_class'],
                                         e['default_autonomy'], 'GATE' if e['hard_gate'] else ''))
