def ensure_tools() -> dict:
    """Seed missing registry rows; return {tool_key: row}. Admin edits to
    enabled / cost_cents on existing rows are preserved."""
    from app.extensions import db
    from app.models.agent_plan import ToolRegistry
    rows = {t.tool_key: t for t in ToolRegistry.query.all()}
    added = False
    for key, (integration, cls, blast, cost, rev, enabled) in TOOL_SEED.items():
        if key not in rows:
            row = ToolRegistry(tool_key=key, integration=integration, side_effect_class=cls,
                               blast_radius=blast, cost_cents=cost, reversible=rev, enabled=enabled)
            db.session.add(row)
            rows[key] = row
            added = True
    if added:
        db.session.commit()
    return rows


