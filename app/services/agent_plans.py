"""Inspectable agent plans, tool registry and autonomy (EXEC_PLAN P3).

P3 is L1 — plan + suggest; P4 adds L2 execution of approved REVERSIBLE steps
(app/services/plan_executor.py). A plan decomposes the agent's strategy (the
``methods`` template in config/agent_execution.json) into steps, each naming a
registered tool with its reversibility, blast radius and estimated cost. Users
approve or reject steps; **nothing executes in P3** — there is deliberately no
code path here that calls a tool. Execution of approved reversible steps comes
in P4, sends in P5.

Plans are built deterministically from the generated config (no model call),
so the same artifact always yields the same plan, and they are created lazily
the first time an artifact's plan is opened.

Invariants enforced here:
  * autonomy is never L4; Layer 5 agents are locked at L0 (generate-only);
    money-movement agents are capped at L1 (execution disabled)
  * hard-gate steps (send, sign, post, trade) always need a human decision
  * disabled tools (no client, legal review, money movement) are unavailable
"""
