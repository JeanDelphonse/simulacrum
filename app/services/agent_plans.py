def _agent_layer(action_type: str) -> int:
    from app.services.agent_registry import get_agent_meta
    meta = get_agent_meta(action_type) or {}
    return int(meta.get('layer') or 0)


def allowed_levels(action_type: str) -> list:
    from app.services import agent_execution
    cfg = agent_execution.get(action_type)
    if _agent_layer(action_type) == 5:
        return ['L0']                                  # generate-only
    if cfg.get('side_effect_class') == 'money_move':
        return ['L0', 'L1']                            # execution disabled
    return list(LEVELS)


def default_level(action_type: str) -> str:
    from app.services import agent_execution
    level = agent_execution.get(action_type).get('default_autonomy') or 'L1'
    allowed = allowed_levels(action_type)
    return level if level in allowed else allowed[-1]


def effective_level(user_id: str, action_type: str) -> str:
    from app.models.agent_plan import AgentAutonomyConfig
    from app.services.agent_registry import resolve_alias
    row = AgentAutonomyConfig.query.filter_by(user_id=user_id,
                                              agent_key=resolve_alias(action_type)).first()
    if row and row.level in allowed_levels(action_type):
        return row.level
    return default_level(action_type)


def set_level(user_id: str, action_type: str, level: str) -> str:
    from app.extensions import db
    from app.models.agent_plan import AgentAutonomyConfig
    from app.models.audit_log import AuditLog
    from app.services.agent_registry import resolve_alias
    agent = resolve_alias(action_type)
    if level not in allowed_levels(agent):
        raise ValueError('%s is not allowed for %s (allowed: %s)' % (
            level, agent, ', '.join(allowed_levels(agent))))
    row = AgentAutonomyConfig.query.filter_by(user_id=user_id, agent_key=agent).first()
    if row is None:
        row = AgentAutonomyConfig(user_id=user_id, agent_key=agent, level=level)
        db.session.add(row)
    else:
        row.level = level
    AuditLog.log('agent_autonomy_set', user_id=user_id, resource_id=agent, metadata={'level': level})
    db.session.commit()
    return level


def autonomy_overview(user_id: str) -> list:
    from app.services import agent_execution
    from app.services.agent_registry import get_all_agents
    out = []
    for a in get_all_agents():
        at = a['action_type']
        cfg = agent_execution.get(at)
        out.append({
            'agent_key': at, 'label': a['label'], 'layer': a['layer'],
            'side_effect_class': cfg.get('side_effect_class'), 'hard_gate': cfg.get('hard_gate'),
            'default_level': default_level(at), 'level': effective_level(user_id, at),
            'allowed_levels': allowed_levels(at),
        })
    return out


