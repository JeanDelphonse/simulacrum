def _required_reason(tool) -> str | None:
    if tool is None:
        return None
    if tool.side_effect_class in _HARD_GATE:
        return 'hard_gate'
    if not tool.reversible:
        return 'irreversible'
    if tool.blast_radius >= 2:
        return 'blast'
    return None


def build_plan(action, user_id: str):
    """Create a plan for an artifact from its agent's method template."""
    from app.extensions import db
    from app.models.agent_plan import AgentPlan, PlanStep
    from app.models.artifact import ArtifactVersion
    from app.services import agent_execution
    from app.services.agent_registry import get_agent_meta, resolve_alias

    agent = resolve_alias(action.action_type)
    cfg = agent_execution.get(agent)
    meta = get_agent_meta(agent) or {}
    tools = ensure_tools()
    level = effective_level(user_id, agent)
    suggested = set(cfg.get('suggested_tools') or [])
    method = cfg.get('methods') or {'name': 'generate_only', 'steps': ['generate', 'refine', 'export']}
    current = ArtifactVersion.current_for(action.id)

    plan = AgentPlan(agent_key=agent, simulation_id=action.simulation_id, action_id=action.id,
                     user_id=user_id, method=method['name'], autonomy_level=level,
                     goal='%s — %s' % (meta.get('label', agent), meta.get('description', '')))
    db.session.add(plan)
    db.session.flush()
    for n, verb in enumerate(method['steps']):
        candidates, expected = _STEP_TOOLS.get(verb, ((), verb.replace('_', ' ').capitalize()))
        tool_key = next((t for t in candidates if t in suggested), None)
        tool = tools.get(tool_key) if tool_key else None
        reason = _required_reason(tool)
        if tool is None:
            status = PlanStep.APPROVAL_NOT_REQUIRED
        elif not tool.enabled:
            status = 'unavailable'
        elif level == 'L0':
            status = PlanStep.APPROVAL_NOT_REQUIRED     # generate-only: informational
        elif reason or level in ('L1', 'L2') or _is_executable(tool_key, tool):
            # Executable steps always take their own approval in P4: plan-level
            # approval (L3) isn't built yet, so nothing runs without a step OK.
            status = PlanStep.APPROVAL_PENDING
        else:
            status = PlanStep.APPROVAL_NOT_REQUIRED     # L3: covered by plan approval
        step = PlanStep(plan_id=plan.id, seq_index=n, tool_key=tool_key, method=verb,
                        expected=expected,
                        reversibility=('reversible' if (tool is None or tool.reversible) else 'irreversible'),
                        blast=tool.blast_radius if tool else 0,
                        est_cost_cents=tool.cost_cents if tool else 0,
                        required_reason=reason, approval_status=status)
        step.inputs = {'artifact_id': action.id,
                       'version': current.version_number if current else None}
        db.session.add(step)
    db.session.commit()
    _escalate_executable_steps(plan, action, level)
    return plan


def _is_executable(tool_key, tool) -> bool:
    from app.services.plan_executor import EXECUTABLE_TOOLS
    return bool(tool is not None and tool_key in EXECUTABLE_TOOLS and tool.enabled)


def _escalate_executable_steps(plan, action, level: str) -> None:
    """Surface steps that could run (L2+) in the Escalations queue — one item
    per step, resolved when the user decides or runs it."""
    if level not in ('L2', 'L3'):
        return
    from app.models.agent_plan import PlanStep
    from app.services.agent_registry import get_agent_meta
    try:
        from utils.action_items import create_action_item
        label = (get_agent_meta(plan.agent_key) or {}).get('label', plan.agent_key)
        for st in PlanStep.query.filter_by(plan_id=plan.id,
                                           approval_status=PlanStep.APPROVAL_PENDING).all():
            if st.tool_key not in _executable_keys():
                continue
            create_action_item(
                simulation_id=plan.simulation_id, user_id=plan.user_id,
                item_type='agent_approval_required',
                title=('Approve: %s — %s' % (st.tool_key.replace('_', ' '), label))[:200],
                description='The agent proposes this reversible step. Nothing runs until you approve it '
                            'and press Run on the artifact\'s plan.',
                action_url='/simulations/%s/artifacts/%s' % (plan.simulation_id, plan.action_id),
                layer_number=action.layer_number, source_action_id=plan.action_id,
                source_artifact_id=st.id)
    except Exception as exc:
        logger.warning('plan escalation failed for plan %s: %s', plan.id, exc)


def _executable_keys():
    from app.services.plan_executor import EXECUTABLE_TOOLS
    return EXECUTABLE_TOOLS


def resolve_escalation(step_id: str) -> None:
    try:
        from app.models.layer6 import ActionItem
        from utils.action_items import resolve_action_item
        for item in ActionItem.query.filter_by(source_artifact_id=step_id,
                                               item_type='agent_approval_required',
                                               resolved_at=None).all():
            resolve_action_item(item.id)
    except Exception as exc:
        logger.warning('could not resolve escalation for step %s: %s', step_id, exc)


def current_plan(action_id: str):
    from app.models.agent_plan import AgentPlan
    return (AgentPlan.query.filter(AgentPlan.action_id == action_id,
                                   AgentPlan.status != AgentPlan.STATUS_SUPERSEDED)
            .order_by(AgentPlan.created_at.desc()).first())


def get_or_create_plan(action, user_id: str):
    return current_plan(action.id) or build_plan(action, user_id)


def regenerate_plan(action, user_id: str):
    from app.extensions import db
    from app.models.agent_plan import AgentPlan
    old = current_plan(action.id)
    if old is not None:
        old.status = AgentPlan.STATUS_SUPERSEDED
        db.session.commit()
    return build_plan(action, user_id)


def _refresh_status(plan) -> None:
    from app.models.agent_plan import AgentPlan, PlanStep
    statuses = [s.approval_status for s in PlanStep.query.filter_by(plan_id=plan.id).all()]
    if PlanStep.APPROVAL_REJECTED in statuses:
        plan.status = AgentPlan.STATUS_REJECTED
    elif PlanStep.APPROVAL_PENDING in statuses:
        plan.status = AgentPlan.STATUS_PROPOSED
    elif PlanStep.APPROVAL_APPROVED in statuses:
        plan.status = AgentPlan.STATUS_APPROVED
    else:
        plan.status = AgentPlan.STATUS_PROPOSED


def decide(step_id: str, user_id: str, decision: str):
    """Record approve/reject on a pending step. Records only — in P3 an
    approval never triggers execution."""
    from app.extensions import db
    from app.models.agent_plan import ActionApproval, AgentPlan, PlanStep
    if decision not in ('approve', 'reject'):
        raise ValueError('decision must be approve or reject')
    step = PlanStep.query.get(step_id)
    plan = AgentPlan.query.get(step.plan_id) if step else None
    if step is None or plan is None or plan.user_id != user_id:
        raise PermissionError('not your plan')
    if plan.status == AgentPlan.STATUS_SUPERSEDED:
        raise ValueError('This plan was replaced by a newer one.')
    if step.approval_status not in (PlanStep.APPROVAL_PENDING, PlanStep.APPROVAL_APPROVED,
                                    PlanStep.APPROVAL_REJECTED):
        raise ValueError('This step does not take an approval.')
    step.approval_status = (PlanStep.APPROVAL_APPROVED if decision == 'approve'
                            else PlanStep.APPROVAL_REJECTED)
    db.session.add(ActionApproval(target_type='plan_step', target_id=step.id,
                                  required_reason=step.required_reason, decided_by=user_id,
                                  decision=decision))
    _refresh_status(plan)
    db.session.commit()
    if decision == 'reject':
        resolve_escalation(step.id)
    return plan


def plan_dict(plan) -> dict:
    from app.models.agent_action import AgentAction
    from app.models.agent_plan import ExecutionRun, PlanStep
    from app.services import plan_executor
    tools = ensure_tools()
    steps = PlanStep.query.filter_by(plan_id=plan.id).order_by(PlanStep.seq_index).all()
    action = AgentAction.query.get(plan.action_id) if plan.action_id else None
    level_now = effective_level(plan.user_id, plan.agent_key) if plan.user_id else plan.autonomy_level
    runs = {}
    for r in (ExecutionRun.query.filter(ExecutionRun.step_id.in_([s.id for s in steps]))
              .order_by(ExecutionRun.created_at.desc()).all() if steps else []):
        runs.setdefault(r.step_id, r.to_dict())
    return {
        'id': plan.id, 'agent_key': plan.agent_key, 'goal': plan.goal, 'method': plan.method,
        'autonomy_level': plan.autonomy_level,
        'autonomy_label': LEVEL_LABELS.get(plan.autonomy_level, plan.autonomy_level),
        'status': plan.status, 'created_at': plan.created_at.isoformat(),
        # P4: only approved reversible steps can run, and only at L2+.
        'executes': level_now in ('L2', 'L3') and any(
            plan_executor.executable(s, tools.get(s.tool_key)) for s in steps),
        'level_now': level_now,
        'steps': [{
            'id': s.id, 'seq': s.seq_index + 1, 'method': s.method, 'tool_key': s.tool_key,
            'tool_integration': tools[s.tool_key].integration if s.tool_key in tools else None,
            'expected': s.expected, 'reversibility': s.reversibility, 'blast': s.blast,
            'est_cost_cents': s.est_cost_cents, 'required_reason': s.required_reason,
            'approval_status': s.approval_status,
            'executable': plan_executor.executable(s, tools.get(s.tool_key)),
            'default_inputs': (plan_executor.default_inputs(s.tool_key, action)
                               if plan_executor.executable(s, tools.get(s.tool_key)) else None),
            'last_run': runs.get(s.id),
        } for s in steps],
    }
